export function t(key: string) {
  const d = I18N[lang] || I18N.en
  return d[key] !== undefined ? d[key] : (I18N.en[key] !== undefined ? I18N.en[key] : key)
}

export function setLang(l: "en" | "ro") {
  lang = (l === 'en' || l === 'ro') ? l : 'ro'
  try {
    localStorage.setItem(LANG_KEY, lang)
  } catch (e) {}
}

export function toggleLang() {
  setLang(lang === 'ro' ? 'en' : 'ro')
}

const listeners = new Set<() => void>()

export function setLangNow(l: 'en' | 'ro') {
  setLang(l)
  listeners.forEach(f => f())
}

export function toggleLangNow() {
  setLangNow(lang === 'ro' ? 'en' : 'ro')
}

export function onLangChange(fn: () => void) {
  listeners.add(fn)
  return () => { listeners.delete(fn) }
}
